# ── _add_heading_markers ────────────────────────────────────────────────

class TestAddHeadingMarkers:
    def test_top_level(self):
        md = "1. Introduction"
        result = FormatStage._add_heading_markers(md)
        assert result == "# 1. Introduction"

    def test_sub_heading(self):
        md = "1.2 Section"
        result = FormatStage._add_heading_markers(md)
        assert result == "## 1.2 Section"

    def test_deep_heading(self):
        md = "1.2.3 Subsection"
        result = FormatStage._add_heading_markers(md)
        assert result == "### 1.2.3 Subsection"

    def test_bare_sub_heading(self):
        md = "1.2\n"
        result = FormatStage._add_heading_markers(md)
        assert result.startswith("## 1.2")

    def test_bare_top_heading(self):
        md = "1.\n"
        result = FormatStage._add_heading_markers(md)
        assert result.startswith("# 1.")

    def test_idempotent_on_existing_markers(self):
        md = "# 1. Introduction"
        result = FormatStage._add_heading_markers(md)
        # Should NOT double the # mark
        assert result == "# 1. Introduction"


