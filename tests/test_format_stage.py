"""Tests for FormatStage — regex transforms, heading renumbering, cost calc."""

from __future__ import annotations

import logging
from pathlib import Path

import pytest

from src.components.publisher.rapporteur_cli import FormatStage

# -- helpers ----------------------------------------------------------------

def _make_format_stage() -> FormatStage:
    stage = object.__new__(FormatStage)
    stage._logger = logging.getLogger("test.format")
    stage.dry_run = False
    return stage


# ── _strip_code_fencing ──────────────────────────────────────────────────

class TestStripCodeFencing:
    def test_strips_markdown_fences(self):
        text = "```markdown\n# Hello\n```"
        assert FormatStage._strip_code_fencing(text) == "# Hello"

    def test_strips_plain_fences(self):
        text = "```\nContent\n```"
        assert FormatStage._strip_code_fencing(text) == "Content"

    def test_no_fences_unchanged(self):
        text = "# Hello\nWorld"
        assert FormatStage._strip_code_fencing(text) == text

    def test_only_leading_fence(self):
        text = "```md\nContent here"
        assert FormatStage._strip_code_fencing(text) == "Content here"

    def test_only_trailing_fence(self):
        text = "Content here\n```"
        assert FormatStage._strip_code_fencing(text) == "Content here"


# ── _split_refs ──────────────────────────────────────────────────────────

class TestSplitRefs:
    def test_splits_top_sources(self):
        md = "Body text.\n\n## Top Sources\n\n1. Source A\n"
        body, refs = FormatStage._split_refs(md)
        assert "Body text." in body
        assert "## Top Sources" in refs

    def test_splits_references(self):
        md = "Body text.\n\n## References\n\n- Ref1\n"
        body, refs = FormatStage._split_refs(md)
        assert "Body text." in body
        assert "## References" in refs

    def test_no_ref_section(self):
        md = "Just body text.\n\n## Analysis\n\nMore text."
        body, refs = FormatStage._split_refs(md)
        assert body == md
        assert refs == ""

    def test_strips_footer_from_refs(self):
        md = (
            "Body.\n\n## Top Sources\n\n1. Source\n\n"
            "---\n*Generated by Rapporteur CLI v1.0*\n"
        )
        _, refs = FormatStage._split_refs(md)
        assert "Generated by Rapporteur CLI" not in refs


