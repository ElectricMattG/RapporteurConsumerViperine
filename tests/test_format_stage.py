# ── _calculate_cost ──────────────────────────────────────────────────────

class TestCalculateCost:
    def test_gemini_pro_cost(self):
        stage = _make_format_stage()
        cost = stage._calculate_cost("gemini-2.5-pro", 1_000_000, 1_000_000)
        assert cost == pytest.approx(1.25 + 10.00)

    def test_flash_cost(self):
        stage = _make_format_stage()
        cost = stage._calculate_cost("gemini-2.5-flash", 1_000_000, 1_000_000)
        assert cost == pytest.approx(0.30 + 2.50)

    def test_unknown_model_uses_pro_fallback(self):
        stage = _make_format_stage()
        cost = stage._calculate_cost("unknown-model", 1_000_000, 1_000_000)
        # Falls back to gemini-2.5-pro rates
        assert cost == pytest.approx(1.25 + 10.00)

    def test_zero_tokens(self):
        stage = _make_format_stage()
        assert stage._calculate_cost("gemini-2.5-pro", 0, 0) == 0.0


