# ── _load_style_rules ────────────────────────────────────────────────────

class TestLoadStyleRules:
    def test_extracts_section(self, tmp_path):
        stage = _make_format_stage()
        guide = tmp_path / "style.md"
        guide.write_text(
            "# Guide\n\n## STYLE CONVENTIONS\n\nRule 1\nRule 2\n\n## OTHER\nStuff\n"
        )
        result = stage._load_style_rules(guide)
        assert "Rule 1" in result
        assert "OTHER" not in result

    def test_missing_file(self, tmp_path):
        stage = _make_format_stage()
        result = stage._load_style_rules(tmp_path / "nonexistent.md")
        assert result == ""

    def test_no_section_returns_full_text(self, tmp_path):
        stage = _make_format_stage()
        guide = tmp_path / "style.md"
        guide.write_text("Just some text without headers.")
        result = stage._load_style_rules(guide)
        assert result == "Just some text without headers."
